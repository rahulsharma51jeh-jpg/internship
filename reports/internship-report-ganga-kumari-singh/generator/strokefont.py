# ------------------------------------------------------------------ engine ----
def _flatten(paths):
    """Command list -> list of polylines in font units."""
    out = []
    for sub in paths:
        poly = []
        cur = None
        for cmd in sub:
            op = cmd[0]
            if op == 'M':
                if len(poly) > 1:
                    out.append(poly)
                poly = [(cmd[1], cmd[2])]
                cur = (cmd[1], cmd[2])
            elif op == 'L':
                poly.append((cmd[1], cmd[2]))
                cur = (cmd[1], cmd[2])
            elif op == 'A':
                _, cx, cy, rx, ry, a0, a1 = cmd
                span = abs(a1 - a0)
                steps = max(4, int(span / 11.0) + 3)
                first = (cx + rx * math.cos(math.radians(a0)),
                         cy + ry * math.sin(math.radians(a0)))
                if poly and cur and math.hypot(first[0] - cur[0],
                                               first[1] - cur[1]) > JOIN_TOL:
                    out.append(poly)
                    poly = []
                for k in range(steps + 1):
                    a = math.radians(a0 + (a1 - a0) * k / steps)
                    poly.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
                cur = poly[-1]
        if len(poly) > 1:
            out.append(poly)
    return out


_FLAT = {ch: (adv, _flatten(paths)) for ch, (adv, paths) in _G.items()}
_FALLBACK = _FLAT[" "]

_SUBST = {
    "\u00a0": " ", "\u2212": "-", "\u00b7": "\u2022", "\u00e9": "e",
    "\u00ad": "-", "\u2032": "'", "\u00b0": "o",
}


def _entry(ch):
    ch = _SUBST.get(ch, ch)
    e = _FLAT.get(ch)
    if e is None:
        e = _FLAT.get(ch.upper())
    return e or _FALLBACK


def text_width(text, size, tracking=0.0):
    """Advance width of `text` rendered at cap-height `size` pixels."""
    s = size / CAP
    total = sum(_entry(ch)[0] for ch in text) * s
    if len(text) > 1:
        total += tracking * (len(text) - 1)
    return total


def fit_size(text, target_width, tracking_ratio=0.0, max_size=None):
    """
    Largest cap height at which `text` fits `target_width`, where letter
    tracking is `tracking_ratio * size`. Returns (size, tracking).
    """
    if not text:
        return (0.0, 0.0)
    adv = sum(_entry(ch)[0] for ch in text) / CAP
    denom = adv + tracking_ratio * max(0, len(text) - 1)
    size = target_width / denom if denom > 0 else 0.0
    if max_size is not None:
        size = min(size, max_size)
    return (size, size * tracking_ratio)


def draw_text(cv, text, x, y, size, rgb, weight=None, align="left",
              baseline="alphabetic", alpha=1.0, tracking=0.0):
    """
    Stroke `text` onto canvas `cv`.

    x, y are canvas pixels (y down). `y` is the baseline unless `baseline` is
    'middle', 'top' or 'cap'. `size` is the cap height in pixels.
    """
    s = size / CAP
    if weight is None:
        weight = max(0.95, size * 0.118)

    total = text_width(text, size, tracking)
    if align == "center":
        x -= total / 2.0
    elif align == "right":
        x -= total

    if baseline == "middle":
        y += size / 2.0
    elif baseline in ("top", "cap"):
        y += size

    pen = x
    for ch in text:
        adv, polys = _entry(ch)
        for poly in polys:
            pts = [(pen + px * s, y - py * s) for (px, py) in poly]
            if len(pts) == 2 and abs(pts[0][0] - pts[1][0]) < 0.5 and \
                    abs(pts[0][1] - pts[1][1]) < 0.5:
                cv.circle(pts[0][0], pts[0][1], weight * 0.60, rgb, alpha)
            else:
                cv.stroke_polyline(pts, rgb, weight, alpha)
        pen += adv * s + tracking
    return total
